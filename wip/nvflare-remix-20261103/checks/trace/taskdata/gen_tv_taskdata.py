#!/usr/bin/env python3
"""v11 G (taskDataFail) trace validation with a HAND-WRITTEN trace that follows the
code path (eager path: communicator.py:486-500, client_runner.py:613-636); the
client pull loop needs ClientRunner + Communicator + Cell, which no group-level
harness here runs. Replayed against TaskCJ_C with a trace-driven environment
(CJ launch, the SJ's TASK_ASSIGNMENT replies). The negative control replays the
same trace without the fault: the dropped reply must be rejected.

gen_tv_taskdata.py [--run]
"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"

def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    for k in ("p", "g"):
        if k in e:
            f[k] = str(e[k])
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"

TEMPLATE = r'''---- MODULE MC_TraceTD_@NAME@ ----
\* Generated by checks/trace/taskdata/gen_tv_taskdata.py (hand-written code-path trace)
EXTENDS Ports, TLC, Sequences
CONSTANTS s1
VARIABLES taskCJ_c, cur
TC == INSTANCE TaskCJ_C
MCFaults == {@FAULTS@}
MCProfile == {}
TR == << @TR@ >>
EnvKinds == {"launch", "reply"}
Fixed == <<pJobSP, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg, pWorker, pModel, pSwarm>>
GT(p) == MsgKey("GET_TASK", CJ(s1), SJ, <<JobId, s1, 1, p>>)
T1 == taskCJ_c[s1][1]
T1n == taskCJ_c'[s1][1]
Obs == <<GT(1) \in DOMAIN net, GT(2) \in DOMAIN net, GT(3) \in DOMAIN net, T1.got, T1.asg, pTaskCJ[s1][1].input>>
ObsAny == Obs' /= Obs
Match(e) ==
    CASE e.ev = "poll" -> GT(e.p) \in DOMAIN net' /\ GT(e.p) \notin DOMAIN net
      [] e.ev = "dropped" -> T1n.got = e.p /\ T1.got /= e.p /\ T1n.asg = None
      [] e.ev = "assigned" -> T1n.asg /= None /\ T1.asg = None
      [] e.ev = "input" -> pTaskCJ'[s1][1].input /= None /\ pTaskCJ'[s1][1].input.gen = e.g
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<taskCJ_c, pTaskCJ>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "launch" -> /\ pJobCP' = [pJobCP EXCEPT ![s1].launch = 1]
                              /\ pRunCJ' = [pRunCJ EXCEPT ![s1][1].ready = TRUE, ![s1][1].state = "running"]
                              /\ UNCHANGED net
         [] e.ev = "reply" -> /\ net' = Send(net, Msg("TASK_ASSIGNMENT", SJ, CJ(s1), <<JobId, s1, 1, e.p>>,
                                     [status |-> "ASSIGNED", assignment |-> Assignment(s1, 1),
                                      input |-> TaskInput(Assignment(s1, 1))]))
                              /\ UNCHANGED <<pJobCP, pRunCJ>>
TInit == PortsInit /\ TC!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ TC!Next /\ UNCHANGED <<pJobCP, pRunCJ>> /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''
CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  s1 = s1
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 1
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""
if __name__ == "__main__":
    ev = json.loads((HERE / "traces" / "taskdata_eager.json").read_text())
    res = {}
    for name, faults in (("eager", '"taskDataFail"'), ("neg_nofault", "")):
        mod = f"TraceTD_{name}"
        (MIXES / f"MC_{mod}.tla").write_text(TEMPLATE.replace("@NAME@", name).replace("@FAULTS@", faults)
                                             .replace("@TR@", ",\n        ".join(tla_val(e) for e in ev)))
        (MIXES / f"MC_{mod}.cfg").write_text(CFG)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(mod, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[name] = dict(events=len(ev), accepted=acc, result=r.get("result"), distinct=r.get("distinct"), error=r.get("error"))
            print(name, json.dumps(res[name]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
