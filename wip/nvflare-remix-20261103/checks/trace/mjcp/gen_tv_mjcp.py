#!/usr/bin/env python3
"""v11 block F trace validation: a real two-job resource manager run vs JobCP_C (multiJobCP).

Reads traces/<scn>.json (tv_mjcp_test.py) and writes checks/mixes/MC_TraceMJ_<scn>.tla/.cfg:
JobCP_C with a trace-driven environment (our job's CHECK_RESOURCES requests) and
a cursor. Observed: J2's lifecycle on pJobCP and the RESOURCES_OK reply body.
JobCP_C is coarse: acceptance is coarse-grained evidence.

gen_tv_mjcp.py [SCN ...] [--mutate] [--run]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"


def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    if "n" in e:
        f["n"] = str(e["n"])
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceMJ_@SCN@ ----
\* Generated by checks/trace/mjcp/gen_tv_mjcp.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS s1
VARIABLES jobCP_c, cur
CP1 == INSTANCE JobCP_C
MCFaults == {}
MCProfile == {"multiJobCP"}
TR == << @TR@ >>
EnvKinds == {"check"}
Fixed == <<pJobSP, pRunCJ, pTaskCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg, pWorker, pModel, pSwarm>>
RKey == MsgKey("RESOURCES_OK", CP(s1), SP, <<JobId, s1>>)
Rep == IF RKey \in DOMAIN net THEN net[RKey].msg.body ELSE None
Repn == IF RKey \in DOMAIN net' THEN net'[RKey].msg.body ELSE None
Obs == <<pJobCP[s1].j2, Rep>>
ObsAny == Obs' /= Obs
J2n == pJobCP'[s1].j2
Match(e) ==
    CASE e.ev = "j2start" -> J2n.st = "running" /\ J2n.alloc /\ pJobCP[s1].j2.st = "none"
      [] e.ev = "checkno" -> Repn = "no" /\ Rep /= "no"
      [] e.ev = "j2exit" -> J2n.st = "exited" /\ pJobCP[s1].j2.st = "running"
      [] e.ev = "j2free" -> J2n.st = "freed" /\ ~J2n.alloc
      [] e.ev = "checkok" -> Repn = "ok" /\ Rep /= "ok"
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<jobCP_c, pJobCP>> /\ UNCHANGED Fixed
    /\ net' = Send(net, Msg("CHECK_RESOURCES", SP, CP(s1), <<JobId, s1, e.n>>, None))
TInit == PortsInit /\ CP1!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ CP1!Next /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''
CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  s1 = s1
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 1
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    name = f"TraceMJ_{scn}"
    (MIXES / f"MC_{name}.tla").write_text(TEMPLATE.replace("@SCN@", scn).replace(
        "@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


def mutate():
    ok = json.loads((HERE / "traces" / "mjcp_ok.json").read_text())
    neg = [e for e in ok if e["ev"] != "j2start"]                 # busy check with no second job
    (HERE / "traces" / "neg_busy_without_j2.json").write_text(json.dumps(neg, indent=1))
    k = [e["ev"] for e in ok]
    a, b = k.index("j2exit"), k.index("j2free")
    neg2 = list(ok); neg2[a], neg2[b] = neg2[b], neg2[a]          # freed before its CJ exited
    (HERE / "traces" / "neg_free_before_exit.json").write_text(json.dumps(neg2, indent=1))


if __name__ == "__main__":
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
