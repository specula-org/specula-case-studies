#!/usr/bin/env python3
"""Worker-group trace validation (v10): real task-worker runs vs Worker_F.

Reads checks/trace/worker/traces/<scn>.json (tv_worker_test.py) and writes
checks/mixes/MC_TraceWorker_<scn>.tla/.cfg: Worker_F with a trace-driven
environment (CJ launch, TaskCJ input / abort / receipt) and a cursor. Each Worker_F
step either produces the next observed event or is silent (changes nothing the
harness observes). Accepted = the cursor passes the last event, checked as the
witness invariant TraceNotAccepted being violated (BFS).

gen_tv_worker.py [SCN ...] [--run] [--variant F|C]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"
ENV = {"launch", "input", "abort", "receipt"}


def events(scn):
    raw = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    out, last_receipt = [], None
    i = 0
    while i < len(raw):
        e = raw[i]
        k = e["ev"]
        if k == "settled":
            i += 1
            continue  # internal marker: the model step is "validated" or the outcome
        if k == "receipt":
            last_receipt = e
        if k in ("release", "receiptRec"):
            rel = []
            while i < len(raw) and raw[i]["ev"] in ("release", "receiptRec"):
                if raw[i]["ev"] == "release":
                    rel.append(raw[i]["w"])
                i += 1
            out.append(dict(ev="receiptRel", l=last_receipt["l"], gen=last_receipt["gen"], release=rel))
            continue
        out.append(e)
        i += 1
    return out


def tla_val(e):
    k = e["ev"]
    if k == "launch":
        return f'[ev |-> "launch", l |-> {e["l"]}]'
    if k == "input":
        return f'[ev |-> "input", l |-> {e["l"]}, gen |-> {e["gen"]}, a |-> {e["a"]}]'
    if k == "abort":
        return f'[ev |-> "abort", l |-> {e["l"]}]'
    if k == "receipt":
        return f'[ev |-> "receipt", l |-> {e["l"]}, gen |-> {e["gen"]}, body |-> "{e["body"]}"]'
    if k == "stage":
        return f'[ev |-> "stage", w |-> <<{e["w"][0]}, {e["w"][1]}>>]'
    if k == "launched":
        return f'[ev |-> "launched", l |-> {e["l"]}]'
    if k in ("cancelReq", "validated"):
        return f'[ev |-> "{k}", l |-> {e["w"][0]}]'
    if k == "out":
        return (f'[ev |-> "out", l |-> {e["l"]}, gen |-> {e["gen"]}, kind |-> "{e["kind"]}", '
                f'reason |-> "{e["reason"]}", ckpt |-> {"TRUE" if e["ckpt"] else "FALSE"}]')
    if k == "receiptRel":
        rel = ", ".join(f"<<{w[0]}, {w[1]}>>" for w in e["release"])
        return f'[ev |-> "receiptRel", l |-> {e["l"]}, gen |-> {e["gen"]}, release |-> {{{rel}}}]'
    raise ValueError(k)


TEMPLATE = r'''---- MODULE MC_TraceWorker_@SCN@ ----
\* Generated by checks/trace/worker/gen_tv_worker.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
VARIABLES @VAR@, cur
W == INSTANCE Worker_@V@ WITH worker_@v@ <- @VAR@
MCFaults == {"workerCrash", "workerFail"}
MCProfile == {"taskMode"}
C1 == CHOOSE c \in Sites : TRUE
Others == <<net, pJobSP, pJobCP, pRunCJ, pTaskCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg>>
TR == << @TR@ >>
EnvKinds == {"launch", "input", "abort", "receipt"}
PC(l) == @PC@
PCn(l) == @PCN@
RC(l) == @RC@
RCn(l) == @RCN@
Out(l) == pWorker[C1].out[l]
Outn(l) == pWorker'[C1].out[l]
Created(w) == pWorker[C1].store[w].created
Createdn(w) == pWorker'[C1].store[w].created
Dropped(w) == pWorker[C1].store[w].payload /\ ~pWorker'[C1].store[w].payload
ObsAny == \/ \E w \in WAttempts : Createdn(w) /\ ~Created(w)
          \/ \E l \in Launches : \/ PC(l) = "launching" /\ PCn(l) = "waiting"
                                 \/ PCn(l) = "cancel" /\ PC(l) /= "cancel"
                                 \/ PCn(l) = "validated" /\ PC(l) /= "validated"
                                 \/ Outn(l) /= Out(l)
                                 \/ RCn(l) /= RC(l)
Match(e) ==
    CASE e.ev = "stage" -> Createdn(e.w) /\ ~Created(e.w)
      [] e.ev = "launched" -> PC(e.l) = "launching" /\ PCn(e.l) = "waiting"
      [] e.ev = "cancelReq" -> PCn(e.l) = "cancel" /\ PC(e.l) /= "cancel"
      [] e.ev = "validated" -> PCn(e.l) = "validated" /\ PC(e.l) /= "validated"
      [] e.ev = "out" -> /\ Outn(e.l) /= Out(e.l) /\ Outn(e.l) /= None
                         /\ Outn(e.l).gen = e.gen /\ Outn(e.l).kind = e.kind /\ Outn(e.l).reason = e.reason
                         /\ PCn(e.l) = "idle"
                         /\ (pWorker'[C1].ckpt /= pWorker[C1].ckpt) = e.ckpt
      [] e.ev = "receiptRel" -> /\ RCn(e.l) = e.gen /\ RC(e.l) < e.gen
                                /\ \A w \in WAttempts : Dropped(w) = (w \in e.release)
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<@VAR@, pWorker, net, pJobSP, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg>>
    /\ CASE e.ev = "launch" ->
              /\ pJobCP' = [pJobCP EXCEPT ![C1].launch = e.l]
              /\ pRunCJ' = IF e.l > 1 THEN [pRunCJ EXCEPT ![C1][e.l - 1].exit = "crash"] ELSE pRunCJ
              /\ UNCHANGED pTaskCJ
         [] e.ev = "input" ->
              /\ pTaskCJ' = [pTaskCJ EXCEPT ![C1][e.l].input =
                               [gen |-> e.gen, assignment |-> Assignment(C1, e.a),
                                value |-> TaskInput(Assignment(C1, e.a))]]
              /\ UNCHANGED <<pJobCP, pRunCJ>>
         [] e.ev = "abort" ->
              /\ pTaskCJ' = [pTaskCJ EXCEPT ![C1][e.l].abort = TRUE]
              /\ UNCHANGED <<pJobCP, pRunCJ>>
         [] e.ev = "receipt" ->
              /\ pTaskCJ' = [pTaskCJ EXCEPT ![C1][e.l].receipt = [gen |-> e.gen, body |-> e.body]]
              /\ UNCHANGED <<pJobCP, pRunCJ>>
TInit == PortsInit /\ W!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ W!Next /\ UNCHANGED Others
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''

CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  None = None
  JobId = JobId
  MaxLaunch = 2
  MaxAttempt = 2
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def gen(scn, variant="F"):
    ev = events(scn)
    var = "worker_f" if variant == "F" else "worker_c"
    if variant == "F":
        pc = ('worker_f[C1].sup[l].pc', "worker_f'[C1].sup[l].pc", 'worker_f[C1].sup[l].rcpt', "worker_f'[C1].sup[l].rcpt")
    else:
        raise SystemExit("only F has the CJ supervisor state the harness observes")
    name = f"TraceWorker_{scn}"
    t = (TEMPLATE.replace("@SCN@", scn).replace("@VAR@", var).replace("@V@", variant).replace("@v@", variant.lower())
         .replace("@TR@", ",\n        ".join(tla_val(e) for e in ev))
         .replace("@PC@", pc[0]).replace("@PCN@", pc[1]).replace("@RC@", pc[2]).replace("@RCN@", pc[3]))
    (MIXES / f"MC_{name}.tla").write_text(t)
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
