#!/usr/bin/env python3
"""v11 block D trace validation: a real two-site Swarm run vs Swarm_C.

Reads traces/<scn>.events.jsonl (hooks/sitecustomize.py, run_harness.sh),
normalizes it into model events (traces/<scn>.json) and writes
checks/mixes/MC_TraceSwarm_<scn>.tla/.cfg: Swarm_C for both sites with a
trace-driven environment (CJ launch, the server's config / start tasks as
TaskCJ input, END_WF) and a cursor. Swarm_C is coarse: acceptance is
coarse-grained evidence.

Normalization (log points differ from model steps): rounds are shifted by one
(start_round 0 -> model round 1); the starter's local learn task and its start
reply are one model step (start); an aggregator's own submission is one step
(submitted: learn done + replied) followed by accept; a remote submitter's
"submitted" (logged after the aux reply) is moved before the aggregator's
reply; gdone carries the next round's aggregator from the aggregator's local
learn task of round r+1.

gen_tv_swarm.py [SCN ...] [--mutate] [--run]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"
ENV = {"launch", "input", "endwf"}


def normalize(raw):
    raw = sorted(raw, key=lambda e: e["t"])
    starter = next(e["c"] for e in raw if e["ev"] == "start")
    S = lambda name: "A" if name == starter else "B"
    out = [dict(ev="launch")]
    for c in ("A", "B"):
        out.append(dict(ev="input", c=c, r=1))
    pending_start = None
    i = 0
    skip = set()
    for k, e in enumerate(raw):
        if k in skip:
            continue
        ev = e["ev"]
        if ev == "cfg":
            out.append(dict(ev="cfg", c=S(e["c"])))
            if all(x["ev"] != "cfg" for x in raw[k + 1:]):
                out.append(dict(ev="input", c="A", r=2))
        elif ev == "learnq":
            r = e["r"] + 1
            # starter's local round-1 task: part of start
            if e["c"] == starter and r == 1 and pending_start is None:
                pending_start = dict(ev="start", c="A", r=1, g=S(e["aggr"]))
                out.append(pending_start)
            # aggregator's local task for the next round: part of its gdone
            elif any(x.get("ev") == "gdone" and x.get("c") == S(e["c"]) and x.get("r") == r - 1 and "n" not in x
                     for x in out):
                g = next(x for x in reversed(out) if x.get("ev") == "gdone" and x.get("c") == S(e["c"]))
                g["n"] = S(e["aggr"])
            else:
                out.append(dict(ev="learn", c=S(e["c"]), r=r, g=S(e["aggr"])))
        elif ev == "start":
            continue
        elif ev == "trained":
            out.append(dict(ev="trained", c=S(e["c"]), r=e["r"] + 1))
        elif ev == "reply":
            g, d, r = S(e["c"]), S(e["frm"]), e["r"] + 1
            if g == d:
                out.append(dict(ev="submitted", c=d, r=r))     # local submission = replied
            else:
                out.append(dict(ev="submitted", c=d, r=r))     # remote submitter, moved before the reply
                out.append(dict(ev="reply", c=g, d=d, r=r))
        elif ev == "accept":
            out.append(dict(ev="accept", c=S(e["c"]), d=S(e["frm"]), r=e["r"] + 1))
        elif ev == "submitted":
            continue
        elif ev == "gdone":
            out.append(dict(ev="gdone", c=S(e["c"]), r=e["r"] + 1))
        elif ev == "ended":
            if not any(x["ev"] == "endwf" for x in out):
                out.append(dict(ev="endwf"))
            out.append(dict(ev="ended", c=S(e["c"])))
    for x in out:
        if x["ev"] == "gdone":
            x.setdefault("n", "none")
    return out


def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    for key in ("c", "d", "g", "n"):
        if key in e:
            f[key] = f'"{e[key]}"'
    if "r" in e:
        f["r"] = str(e["r"])
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceSwarm_@SCN@ ----
\* Generated by checks/trace/swarm/gen_tv_swarm.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS s1, s2
VARIABLES swarm_c, cur
SW == INSTANCE Swarm_C
MCFaults == {}
MCProfile == {"swarm"}
\* "A" is the starting client of the real run, "B" the other site
St(x) == IF x = "A" THEN Starter ELSE CHOOSE c \in Sites : c /= Starter
TR == << @TR@ >>
EnvKinds == {"launch", "input", "endwf"}
Fixed == <<pJobSP, pRunCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg, pWorker, pModel>>
Q(c) == pSwarm[c][1]
Qn(c) == pSwarm'[c][1]
View(r) == [f \in DOMAIN r \ {"sent", "sentRep"} |-> r[f]]
Obs == [c \in Sites |-> View(Q(c))]
ObsAny == Obs' /= Obs
Others(x) == \A d \in Sites \ {St(x)} : View(Qn(d)) = View(Q(d))
Match(e) ==
    LET c == St(e.c) IN
    /\ Others(e.c)
    /\ CASE e.ev = "cfg" -> Qn(c).cfg /\ ~Q(c).cfg
         [] e.ev = "start" -> /\ Qn(c).reply = [round |-> 2, rc |-> "OK"]
                              /\ Qn(c).learn = [r |-> e.r, st |-> "busy", aggr |-> St(e.g)]
         [] e.ev = "learn" -> Qn(c).learn = [r |-> e.r, st |-> "busy", aggr |-> St(e.g)] /\ Q(c).learn /= Qn(c).learn
         [] e.ev = "trained" -> Qn(c).learn.st = "trained" /\ Qn(c).learn.r = e.r /\ Q(c).learn.st = "busy"
         [] e.ev = "submitted" -> Qn(c).learn.st = "done" /\ Q(c).learn.st = "trained" /\ Qn(c).learn.r = e.r
         [] e.ev = "reply" -> /\ Q(c).gather /= None /\ Q(c).gather.r = e.r
                              /\ Qn(c).gather.replied = Q(c).gather.replied \cup {St(e.d)}
                              /\ St(e.d) \notin Q(c).gather.replied
         [] e.ev = "accept" -> /\ Q(c).gather /= None /\ Q(c).gather.r = e.r
                               /\ Qn(c).gather.gathered = Q(c).gather.gathered \cup {St(e.d)}
                               /\ St(e.d) \notin Q(c).gather.gathered
         [] e.ev = "gdone" -> /\ Q(c).aggregated[e.r] = None /\ Qn(c).aggregated[e.r] /= None
                              /\ IF e.n = "none" THEN Qn(c).report.allDone
                                 ELSE Qn(c).learn = [r |-> e.r + 1, st |-> "busy", aggr |-> St(e.n)]
         [] e.ev = "ended" -> Qn(c).ended /\ ~Q(c).ended
         [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<swarm_c, pSwarm>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "launch" -> /\ pJobCP' = [c \in Sites |-> [pJobCP[c] EXCEPT !.launch = 1]]
                              /\ UNCHANGED <<pTaskCJ, net>>
         [] e.ev = "input" -> /\ pTaskCJ' = [pTaskCJ EXCEPT ![St(e.c)][1].input =
                                    [gen |-> e.r, assignment |-> Assignment(St(e.c), e.r),
                                     value |-> TaskInput(Assignment(St(e.c), e.r))]]
                              /\ UNCHANGED <<pJobCP, net>>
         [] e.ev = "endwf" -> /\ net' = SendAll(net, {Msg("SWARM_END_WF", SJ, CJ(c), <<JobId, c>>, None) : c \in Sites})
                              /\ UNCHANGED <<pJobCP, pTaskCJ>>
TInit == PortsInit /\ SW!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ SW!Next /\ UNCHANGED <<pJobCP, pTaskCJ>> /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''
CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1, s2}
  s1 = s1
  s2 = s2
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 2
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    name = f"TraceSwarm_{scn}"
    (MIXES / f"MC_{name}.tla").write_text(TEMPLATE.replace("@SCN@", scn).replace(
        "@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


def mutate():
    ok = json.loads((HERE / "traces" / "swarm_ok.json").read_text())
    k = next(i for i, e in enumerate(ok) if e["ev"] == "learn")
    t = next(i for i, e in enumerate(ok) if e["ev"] == "trained" and e["c"] == ok[k]["c"] and e["r"] == ok[k]["r"])
    neg = list(ok); neg[k], neg[t] = neg[t], neg[k]          # trained before the learn task arrived
    (HERE / "traces" / "neg_trained_before_learn.json").write_text(json.dumps(neg, indent=1))
    g = next(i for i, e in enumerate(ok) if e["ev"] == "gdone")
    rp = next(i for i, e in enumerate(ok) if e["ev"] == "reply")
    neg2 = list(ok); x = neg2.pop(g); neg2.insert(rp, x)      # round closed before the remote reply
    (HERE / "traces" / "neg_gdone_before_reply.json").write_text(json.dumps(neg2, indent=1))
    neg3 = [dict(e, g=("B" if e["g"] == "A" else "A")) if e["ev"] == "learn" else e for e in ok]  # wrong aggregator
    (HERE / "traces" / "neg_wrong_aggregator.json").write_text(json.dumps(neg3, indent=1))


if __name__ == "__main__":
    for p in sorted((HERE / "traces").glob("*.events.jsonl")):
        scn = p.name[: -len(".events.jsonl")]
        raw = [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
        (HERE / "traces" / f"{scn}.json").write_text(json.dumps(normalize(raw), indent=1))
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
