#!/usr/bin/env python3
"""v11 block E trace validation: real K8s handle + workspace transfer runs vs JobCP_C (k8sJob).

Reads checks/trace/k8s/traces/<scn>.json (tv_k8s_test.py) and writes
checks/mixes/MC_TraceK8s_<scn>.tla/.cfg: JobCP_C with a trace-driven
environment (the SP's CHECK / DEPLOY / START / ABORT messages, the CJ's exit) and
a cursor. Observed: launch, workspace record, publish handler and exit status
of launch 1 on pJobCP. JobCP_C is coarse: acceptance is coarse-grained evidence.

gen_tv_k8s.py [SCN ...] [--mutate] [--run]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"


def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    if "l" in e:
        f["l"] = str(e["l"])
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceK8s_@SCN@ ----
\* Generated by checks/trace/k8s/gen_tv_k8s.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS s1
VARIABLES jobCP_c, cur
CP1 == INSTANCE JobCP_C
MCFaults == {@FAULTS@}
MCProfile == {"k8sJob"}
TR == << @TR@ >>
EnvKinds == {"sp", "cjexit", "abort"}
Fixed == <<pJobSP, pTaskCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pReg, pWorker, pModel, pSwarm>>
J == pJobCP[s1]
Jn == pJobCP'[s1]
Obs == <<J.launch, J.ws, J.pub, J.exitSeen>>
ObsAny == Obs' /= Obs
SPMsg(kind) == Msg(kind, SP, CP(s1), <<JobId, s1>>, None)
Match(e) ==
    CASE e.ev = "launch" -> Jn.launch = e.l /\ Jn.ws = e.l /\ J.launch /= e.l
      [] e.ev = "pubstart" -> Jn.pub[e.l] = "running" /\ J.pub[e.l] = "none"
      [] e.ev = "pubdone" -> Jn.pub[e.l] = "done" /\ Jn.ws = 0 /\ J.pub[e.l] = "running"
      [] e.ev = "exit" -> Jn.exitSeen[e.l] = "ok" /\ J.exitSeen[e.l] = "none"
      [] e.ev = "deletefail" -> Jn.exitSeen[e.l] = "killed" /\ Jn.ws = 0 /\ J.exitSeen[e.l] = "none"
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<jobCP_c, pJobCP>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "sp" -> /\ net' = SendAll(net, {SPMsg("CHECK_RESOURCES"), SPMsg("DEPLOY_JOB"), SPMsg("START_JOB")})
                           /\ UNCHANGED pRunCJ
         [] e.ev = "abort" -> net' = Send(net, SPMsg("ABORT_JOB")) /\ UNCHANGED pRunCJ
         [] e.ev = "cjexit" -> /\ pRunCJ' = [pRunCJ EXCEPT ![s1][1].exit = "ok", ![s1][1].state = "exited"]
                               /\ UNCHANGED net
TInit == PortsInit /\ CP1!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ CP1!Next /\ UNCHANGED pRunCJ /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''
CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  s1 = s1
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 1
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    faults = '"podDeleteFail", "abort"' if "deletefail" in scn else ""
    name = f"TraceK8s_{scn}"
    (MIXES / f"MC_{name}.tla").write_text(TEMPLATE.replace("@SCN@", scn).replace("@FAULTS@", faults).replace(
        "@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


def mutate():
    ok = json.loads((HERE / "traces" / "k8s_ok.json").read_text())
    k = [e["ev"] for e in ok]
    a, b = k.index("pubstart"), k.index("pubdone")
    neg = list(ok); neg[a], neg[b] = neg[b], neg[a]           # record removed before the handler started
    (HERE / "traces" / "neg_pubdone_first.json").write_text(json.dumps(neg, indent=1))
    c, x = k.index("cjexit"), k.index("exit")
    neg2 = list(ok); neg2[c], neg2[x] = neg2[x], neg2[c]       # exit observed while the CJ still runs
    (HERE / "traces" / "neg_exit_before_cjexit.json").write_text(json.dumps(neg2, indent=1))
    df = json.loads((HERE / "traces" / "k8s_deletefail.json").read_text())
    neg3 = [e for e in df if e["ev"] != "abort"]              # Pod delete without an abort request
    (HERE / "traces" / "neg_deletefail_noabort.json").write_text(json.dumps(neg3, indent=1))


if __name__ == "__main__":
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
