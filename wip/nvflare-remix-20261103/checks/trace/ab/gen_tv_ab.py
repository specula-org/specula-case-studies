#!/usr/bin/env python3
"""v11 blocks A+B trace validation: real SAG / Cyclic runs vs WfSJ_C + Model_C.

Reads checks/trace/ab/traces/<scn>.json (tv_ab_test.py) and writes
checks/mixes/MC_TraceAB_<scn>.tla/.cfg: the coarse WfSJ and Model variants with
a trace-driven environment (SJ launch, CommSJ task / APP_CALL / completion /
retirement) and a cursor. Each WfSJ_C / Model_C step either produces the next
observed event or is silent (changes nothing observed). Accepted = the cursor
passes the last event (TraceNotAccepted violated, BFS). Both variants are
coarse, so acceptance is coarse-grained evidence only.

gen_tv_ab.py [SCN ...] [--run]
Negative traces: neg_<name>.json built by mutate() from a positive trace.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"
ENV = {"launch", "task", "call", "complete", "retire"}
PROFILE = {"sag": ["sjModel", "sag"], "cyc": ["sjModel", "cyclic"], "samp": ["sampling"], "sync": []}
SITES = {"sag": 1, "cyc": 2, "samp": 2, "sync": 1}
FAULTS = {"sync": ["sjSyncFail"]}


def tla_val(e):
    k = e["ev"]
    f = {"ev": f'"{k}"'}
    for key in ("r", "c"):
        if key in e:
            f[key] = str(e[key])
    for key in ("out", "kind", "returned", "rc"):
        if key in e:
            f[key] = f'"{e[key]}"'
    if "accepted" in e:
        f["accepted"] = "TRUE" if e["accepted"] else "FALSE"
    if "tg" in e:
        f["tg"] = "{" + ", ".join(str(i) for i in e["tg"]) + "}"
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceAB_@SCN@ ----
\* Generated by checks/trace/ab/gen_tv_ab.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS @SITECONSTS@
VARIABLES wfSJ_c, model_c, cur
WF == INSTANCE WfSJ_C
MD == INSTANCE Model_C
MCFaults == {@FAULTS@}
MCProfile == {@PROFILE@}
S(i) == @SITEMAP@
TR == << @TR@ >>
EnvKinds == {"launch", "task", "call", "complete", "retire"}
Fixed == <<pJobCP, pRunCJ, pTaskCJ, pPaySrc, pPayRcv, pTrainer, pReg, pWorker, pSwarm>>
Obs == <<pWfSJ.sj, pWfSJ.open, pWfSJ.scheduled, pWfSJ.ret, pWfSJ.accepted, pWfSJ.aggregate, pWfSJ.returned,
         pWfSJ.panic, wfSJ_c.saved, pModel>>
ObsAny == Obs' /= Obs
Match(e) ==
    CASE e.ev = "open" -> ~pWfSJ.open /\ pWfSJ'.open
      [] e.ev = "schedule" -> pWfSJ'.scheduled = e.r /\ pWfSJ.scheduled /= e.r
      [] e.ev = "scheduleT" -> /\ pWfSJ'.scheduled = e.r /\ pWfSJ.scheduled /= e.r
                               /\ pWfSJ'.targets = {S(i) : i \in e.tg}
      [] e.ev = "acc" -> pModel'.acc[e.r][S(e.c)] = e.out /\ pModel.acc[e.r][S(e.c)] /= e.out
      [] e.ev = "ret" -> /\ pWfSJ'.ret = [site |-> S(e.c), round |-> e.r] /\ pWfSJ.ret /= pWfSJ'.ret
                         /\ (S(e.c) \in pWfSJ'.accepted) = e.accepted
      [] e.ev = "agg" -> pModel'.agg[e.r] = e.kind /\ pModel.agg[e.r] = "none"
      [] e.ev = "aggregate" -> pWfSJ.aggregate = None /\ pWfSJ'.aggregate /= None
      [] e.ev = "art" -> pModel'.artifact = [round |-> e.r, kind |-> e.kind] /\ pModel.artifact /= pModel'.artifact
      [] e.ev = "syncfail" -> pWfSJ'.sj = "crashed" /\ pWfSJ.sj = "none" /\ ~pWfSJ'.open
      [] e.ev = "saved" -> wfSJ_c'.saved = e.r /\ wfSJ_c.saved /= e.r /\ pWfSJ'.returned = e.returned
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<net, pWfSJ, pModel, wfSJ_c, model_c>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "launch" -> pJobSP' = [pJobSP EXCEPT !.sjLaunched = TRUE] /\ UNCHANGED pCommSJ
         [] e.ev = "task" -> /\ pCommSJ' = [pCommSJ EXCEPT !.round = e.r, !.standing = TRUE,
                                                           !.claimed = {}, !.finished = {}]
                             /\ UNCHANGED pJobSP
         [] e.ev = "call" -> /\ pCommSJ' = [pCommSJ EXCEPT !.call =
                                   [site |-> S(e.c), round |-> e.r, kind |-> "live", key |-> <<"k", e.c, e.r>>,
                                    assignment |-> Assignment(S(e.c), e.r), value |-> None, rc |-> e.rc,
                                    metricKind |-> "none"], !.claimed = @ \cup {S(e.c)}]
                             /\ UNCHANGED pJobSP
         [] e.ev = "complete" -> /\ pCommSJ.call /= None
                                 /\ pCommSJ' = [pCommSJ EXCEPT !.call = None, !.finished = @ \cup {pCommSJ.call.site}]
                                 /\ UNCHANGED pJobSP
         [] e.ev = "retire" -> pCommSJ' = [pCommSJ EXCEPT !.standing = FALSE] /\ UNCHANGED pJobSP
TInit == PortsInit /\ WF!Init /\ MD!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ \/ WF!Next /\ UNCHANGED <<model_c, pModel>>
          \/ MD!Next /\ UNCHANGED <<wfSJ_c, pWfSJ>>
       /\ UNCHANGED <<pJobSP, pCommSJ>> /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''

CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {@SITES@}
  @SITEEQ@
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 2
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def family(scn):
    base = scn[4:] if scn.startswith("neg_") else scn
    for fam in ("cyc", "samp", "sync"):
        if base.startswith(fam):
            return fam
    return "sag"


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    fam = family(scn)
    n = SITES[fam]
    names = [f"s{i}" for i in range(1, n + 1)]
    sitemap = "CASE " + " [] ".join(f"i = {i} -> s{i}" for i in range(1, n + 1)) if n > 1 else "s1"
    name = f"TraceAB_{scn}"
    t = (TEMPLATE.replace("@SCN@", scn).replace("@SITECONSTS@", ", ".join(names))
         .replace("@PROFILE@", ", ".join(f'"{p}"' for p in PROFILE[fam])).replace("@SITEMAP@", sitemap)
         .replace("@FAULTS@", ", ".join(f'"{f}"' for f in FAULTS.get(fam, [])))
         .replace("@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    cfg = (CFG.replace("@SITES@", ", ".join(names))
           .replace("@SITEEQ@", "\n  ".join(f"{x} = {x}" for x in names)))
    (MIXES / f"MC_{name}.tla").write_text(t)
    (MIXES / f"MC_{name}.cfg").write_text(cfg)
    return name, len(ev)


def mutate():
    """Negative controls: one changed event each (the model must reject)."""
    sag = json.loads((HERE / "traces" / "sag_ok.json").read_text())
    i = next(k for k, e in enumerate(sag) if e["ev"] == "retire")
    j = next(k for k, e in enumerate(sag) if e["ev"] == "agg")
    neg = list(sag)
    neg[i], neg[j] = neg[j], neg[i]          # aggregate before the round's task retired
    (HERE / "traces" / "neg_sag_agg_before_retire.json").write_text(json.dumps(neg, indent=1))
    cyc = json.loads((HERE / "traces" / "cyc_ok.json").read_text())
    neg2 = [dict(e, kind="poisoned") if e["ev"] == "art" else e for e in cyc]   # poisoned save without an aggregator
    (HERE / "traces" / "neg_cyc_poisoned_art.json").write_text(json.dumps(neg2, indent=1))
    rej = json.loads((HERE / "traces" / "sag_reject.json").read_text())
    neg3 = [dict(e, kind="clean") if (e["ev"] == "art" and e["r"] == 1) else e for e in rej]  # clean model from a rejected round
    (HERE / "traces" / "neg_sag_reject_clean.json").write_text(json.dumps(neg3, indent=1))
    samp = json.loads((HERE / "traces" / "samp_ok.json").read_text())
    a = next(i for i, e in enumerate(samp) if e["ev"] == "aggregate")
    b = next(i for i, e in enumerate(samp) if e["ev"] == "saved")
    neg4 = list(samp); neg4[a], neg4[b] = neg4[b], neg4[a]      # model saved before the round aggregated
    (HERE / "traces" / "neg_samp_save_before_aggregate.json").write_text(json.dumps(neg4, indent=1))
    sync = json.loads((HERE / "traces" / "sync_fail.json").read_text())
    neg5 = [sync[0], dict(ev="open"), sync[1]]                   # the workflow opened, then the start failed
    (HERE / "traces" / "neg_sync_after_open.json").write_text(json.dumps(neg5, indent=1))


if __name__ == "__main__":
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
