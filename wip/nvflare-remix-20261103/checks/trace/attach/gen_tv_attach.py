#!/usr/bin/env python3
"""v11 block C trace validation: a real Attach run vs Trainer_A.

Reads checks/trace/attach/traces/<scn>.json (tv_attach_test.py) and writes
checks/mixes/MC_TraceAttach_<scn>.tla/.cfg: Trainer_A with a trace-driven
environment (CJ launch, TaskCJ input and stop signal) and a cursor. Observed:
the session opening, received / published / stopped / err on pTrainer.
Accepted = TraceNotAccepted violated (BFS). Trainer_A is written at coarse
granularity, so acceptance is coarse-grained evidence.

gen_tv_attach.py [SCN ...] [--mutate] [--run]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"


def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    if "g" in e and e["g"] is not None:
        f["g"] = str(e["g"])
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceAttach_@SCN@ ----
\* Generated by checks/trace/attach/gen_tv_attach.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS s1
VARIABLES trainer_a, cur
TA == INSTANCE Trainer_A
MCFaults == {}
MCProfile == {}
TR == << @TR@ >>
EnvKinds == {"launch", "input", "stop"}
Fixed == <<net, pJobSP, pRunCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pReg, pWorker, pModel, pSwarm>>
P == pTrainer[s1][1]
Pn == pTrainer'[s1][1]
Obs == <<P.received, P.published, P.stopped, P.err, trainer_a[s1][1].tp>>
ObsAny == Obs' /= Obs
Match(e) ==
    CASE e.ev = "attach" -> trainer_a'[s1][1].tp = "open" /\ trainer_a[s1][1].tp /= "open"
      [] e.ev = "deliver" -> Pn.received = e.g /\ P.received /= e.g
      [] e.ev = "publish" -> Pn.published /= None /\ Pn.published.gen = e.g /\ P.published /= Pn.published
      [] e.ev = "finalize" -> Pn.stopped /\ ~P.stopped
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<trainer_a, pTrainer>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "launch" -> pJobCP' = [pJobCP EXCEPT ![s1].launch = 1] /\ UNCHANGED pTaskCJ
         [] e.ev = "input" -> /\ pTaskCJ' = [pTaskCJ EXCEPT ![s1][1].input =
                                    [gen |-> e.g, assignment |-> Assignment(s1, e.g),
                                     value |-> TaskInput(Assignment(s1, e.g))]]
                              /\ UNCHANGED pJobCP
         [] e.ev = "stop" -> pTaskCJ' = [pTaskCJ EXCEPT ![s1][1].trainerSignal = "stop"] /\ UNCHANGED pJobCP
TInit == PortsInit /\ TA!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ TA!Next /\ UNCHANGED <<pJobCP, pTaskCJ>> /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''
CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  s1 = s1
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 2
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    name = f"TraceAttach_{scn}"
    (MIXES / f"MC_{name}.tla").write_text(TEMPLATE.replace("@SCN@", scn).replace(
        "@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


def mutate():
    ok = json.loads((HERE / "traces" / "attach_ok.json").read_text())
    kinds = [e["ev"] for e in ok]
    i = max(k for k, x in enumerate(kinds) if x == "deliver")
    j = max(k for k, x in enumerate(kinds) if x == "publish")
    neg = list(ok); neg[i], neg[j] = neg[j], neg[i]       # result accepted before its task was delivered
    (HERE / "traces" / "neg_publish_before_deliver.json").write_text(json.dumps(neg, indent=1))
    neg2 = [e for e in ok if e["ev"] != "attach"]          # tasks delivered without a session
    (HERE / "traces" / "neg_no_attach.json").write_text(json.dumps(neg2, indent=1))
    s, f = kinds.index("stop"), kinds.index("finalize")
    neg3 = list(ok); neg3[s], neg3[f] = neg3[f], neg3[s]   # finalize before the stop signal
    (HERE / "traces" / "neg_finalize_before_stop.json").write_text(json.dumps(neg3, indent=1))


if __name__ == "__main__":
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 600, 4, "bfs", (0, 0), "8g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
