#!/usr/bin/env python3
"""Payload refinement / diagnostic harness (independent of other agents' WIP).

Composes payload variants with a CHAOTIC port environment (checks/pay/PayEnv.tla)
that may perform every port change the slice's neighbors can make (trainer
submission, envelope exposure, CJ launch/stop/exit/crash, workflow done, SJ
launch/exit/crash, network loss). This over-approximates every mix
environment on the ports the payload groups read, so a refinement result here
implies the result in every mix (DESIGN.md section 2, assume-guarantee).

pay_ref.py NAME --src F|C --rcv F|C [--check src|rcv|none] [--negative]
            [--faults f1,f2] [--sites N] [--launch N] [--attempt N] [--inv I1,I2]
            [--run] [--timeout S] [--workers N] [--sim DEPTH]
Writes checks/pay/PayH_NAME.{tla,cfg}; with --run, runs TLC through
scripts/tlc.sh and writes checks/pay/results/NAME.json + logs/pay_NAME.log.
"""
import argparse, json, os, re, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "checks" / "pay"
sys.path.insert(0, str(ROOT / "scripts"))
import run_mc  # noqa: E402  (reuse its TLC output parser)

ENV = r'''------------------------------- MODULE PayEnv -------------------------------
\* GENERATED by scripts/pay_ref.py. Chaotic environment for the payload groups:
\* every port change of the slice neighbors that PaySrc/PayRcv read. Writes
\* only pJobSP, pJobCP, pRunCJ, pTaskCJ, pCommSJ, pWfSJ (record EXCEPT, so it
\* is robust to new fields in the neighbors' port records).
EXTENDS Ports

SJLaunch == /\ ~pJobSP.sjLaunched
            /\ pJobSP' = [pJobSP EXCEPT !.sjLaunched = TRUE]
            /\ UNCHANGED <<pJobCP, pRunCJ, pTaskCJ, pCommSJ, pWfSJ>>
CJLaunch(c) == /\ pJobCP[c].launch < MaxLaunch
               /\ (pJobCP[c].launch = 0 \/ ~CJAlive(c, pJobCP[c].launch))
               /\ pJobCP' = [pJobCP EXCEPT ![c].launch = @ + 1]
               /\ UNCHANGED <<pJobSP, pRunCJ, pTaskCJ, pCommSJ, pWfSJ>>
\* Trainer publishes the round-a result: the submission that registration reads
\* (rounds in increasing order within a launch; TaskCJ resets it per task).
Submit(c, l, a) == /\ CJAlive(c, l)
                   /\ pTaskCJ' = [pTaskCJ EXCEPT ![c][l].submission =
                         [assignment |-> Assignment(c, a), value |-> ResultValue(c, a), tx |-> Tx(c, l, a)]]
                   /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pCommSJ, pWfSJ>>
ResetSub(c, l) == /\ CJAlive(c, l) /\ pTaskCJ[c][l].submission /= None
                  /\ pTaskCJ' = [pTaskCJ EXCEPT ![c][l].submission = None]
                  /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pCommSJ, pWfSJ>>
\* RESULT_ENVELOPE of round a sent by CJ (any time after registration of Tx(c, l, a))
\* and exposed by the SJ runner (one exposed envelope per site per round).
Envelope(c, l, a) == /\ SJAlive /\ pPaySrc[c][l].tx[a].registered /= None
                     /\ pCommSJ' = [pCommSJ EXCEPT !.envelopes[c] =
                           [assignment |-> Assignment(c, a),
                            refs |-> {[ref |-> pPaySrc[c][l].tx[a].registered.ref,
                                       source |-> pPaySrc[c][l].tx[a].registered.source, launch |-> l]}]]
                     /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pTaskCJ, pWfSJ>>
ClearEnvelope(c) == /\ SJAlive /\ pCommSJ.envelopes[c] /= None
                    /\ pCommSJ' = [pCommSJ EXCEPT !.envelopes[c] = None]
                    /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pTaskCJ, pWfSJ>>
Stop(c, l) == /\ CJAlive(c, l) /\ pRunCJ[c][l].state /= "stopping"
              /\ pRunCJ' = [pRunCJ EXCEPT ![c][l].state = "stopping"]
              /\ UNCHANGED <<pJobSP, pJobCP, pTaskCJ, pCommSJ, pWfSJ>>
\* client_runner.py:814-821: run-finally DownloadService.shutdown declared by RunCJ.
DSDown(c, l) == /\ CJAlive(c, l) /\ ~pRunCJ[c][l].dsDown
                /\ pRunCJ' = [pRunCJ EXCEPT ![c][l].dsDown = TRUE]
                /\ UNCHANGED <<pJobSP, pJobCP, pTaskCJ, pCommSJ, pWfSJ>>
\* any death of a live CJ (exit, crash, kill, fatal): Env_Pay allows it at any time
Exit(c, l) == /\ CJAlive(c, l)
              /\ pRunCJ' = [pRunCJ EXCEPT ![c][l].state = "exited",
                    ![c][l].exit = IF pRunCJ[c][l].state = "stopping" THEN "ok" ELSE "crash"]
              /\ UNCHANGED <<pJobSP, pJobCP, pTaskCJ, pCommSJ, pWfSJ>>
WfDone == /\ SJAlive /\ ~pWfSJ.done
          /\ pWfSJ' = [pWfSJ EXCEPT !.done = TRUE]
          /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pTaskCJ, pCommSJ>>
\* server_runner.py:235-237: the SJ's own DownloadService.shutdown after END_RUN.
DSShutdown == /\ SJAlive /\ ~pWfSJ.dsShutdown
              /\ pWfSJ' = [pWfSJ EXCEPT !.dsShutdown = TRUE]
              /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pTaskCJ, pCommSJ>>
SJExit == /\ SJAlive
          /\ pWfSJ' = [pWfSJ EXCEPT !.sj = IF pWfSJ.done THEN "exited" ELSE "crashed"]
          /\ UNCHANGED <<pJobSP, pJobCP, pRunCJ, pTaskCJ, pCommSJ>>

Next == \/ SJLaunch \/ WfDone \/ DSShutdown \/ SJExit
        \/ \E c \in Sites : CJLaunch(c) \/ ClearEnvelope(c)
        \/ \E c \in Sites, l \in Launches : Stop(c, l) \/ DSDown(c, l) \/ Exit(c, l) \/ ResetSub(c, l)
        \/ \E c \in Sites, l \in Launches, a \in Attempts : Submit(c, l, a) \/ Envelope(c, l, a)
=============================================================================
'''

PAYKINDS = {"src": '{"PAYLOAD_REPLY"}', "rcv": '{"PAYLOAD_PULL", "RECEIVER_CONFIRM", "RECEIVER_CANCEL"}'}


def port_vars():
    src = (Path(os.environ.get("MIX_SPEC") or (ROOT / "spec")) / "Ports.tla").read_text()
    m = re.search(r"^VARIABLES\s+([^\n]+)", src, flags=re.M)
    return [x.strip() for x in m.group(1).split(",")]


ENV_PORTS = ["pJobSP", "pJobCP", "pRunCJ", "pTaskCJ", "pCommSJ", "pWfSJ"]


def build(a):
    OUT.mkdir(parents=True, exist_ok=True)
    pv = port_vars()
    extra = [p for p in pv if p not in ENV_PORTS + ["net", "pPaySrc", "pPayRcv"]]
    env_text = ENV
    for p in extra:  # neighbors' ports the chaotic env does not drive stay constant
        env_text = env_text.replace("/\\ UNCHANGED <<", "/\\ UNCHANGED <<" + p + ", ")
    (OUT / "PayEnv.tla").write_text(env_text)
    allp = ", ".join(pv)
    def unch(own):
        return "<<" + ", ".join([p for p in pv if p not in own]) + "{rest}>>"
    sv = {"F": "paySrc_f", "C": "paySrc_c"}[a.src]
    rv = {"F": "payRcv_f", "C": "payRcv_c"}[a.rcv]
    mod = f"PayH_{a.name}"
    L = [f"---- MODULE {mod} ----", "EXTENDS Ports, TLC",
         f"VARIABLES {sv}, {rv}, net_l",
         f"Src == INSTANCE PaySrc_{a.src}", f"Rcv == INSTANCE PayRcv_{a.rcv}", "Env == INSTANCE PayEnv",
         "EPay == INSTANCE Env_Pay",
         f"vars == <<portVars, {sv}, {rv}, net_l>>",
         "Init == PortsInit /\\ Src!Init /\\ Rcv!Init /\\ net_l = 0",
         "NetKeep == DOMAIN net \\subseteq DOMAIN net' /\\ \\A k \\in DOMAIN net : net'[k] = net[k]",
         "NetOK(ks) == NetKeep /\\ \\A k \\in DOMAIN net' \\ DOMAIN net : net'[k].msg.kind \\in ks /\\ ~net'[k].lost",
         "SrcStep == Src!Next /\\ UNCHANGED " + unch(["net", "pPaySrc"]).format(rest=f", {rv}, net_l")
         + ' /\\ Assert(NetOK({"PAYLOAD_REPLY"}), "net discipline PaySrc")',
         "RcvStep == Rcv!Next /\\ UNCHANGED " + unch(["net", "pPayRcv"]).format(rest=f", {sv}, net_l")
         + ' /\\ Assert(NetOK({"PAYLOAD_PULL", "RECEIVER_CONFIRM", "RECEIVER_CANCEL"}), "net discipline PayRcv")',
         "EnvStep == Env!Next /\\ UNCHANGED " + unch(ENV_PORTS).format(rest=f", {sv}, {rv}, net_l"),
         "LoseStep == /\\ \"netLoss\" \\in Faults /\\ net_l < 1",
         "            /\\ \\E k \\in DOMAIN net : ~net[k].lost /\\ net' = [net EXCEPT ![k].lost = TRUE]",
         "            /\\ net_l' = net_l + 1",
         "            /\\ UNCHANGED " + unch(["net"]).format(rest=f", {sv}, {rv}"),
         "Next == SrcStep \\/ RcvStep \\/ EnvStep \\/ LoseStep",
         "Spec == Init /\\ [][Next]_vars",
         "SentKinds(ks) == {net[k].msg : k \\in {k2 \\in DOMAIN net : net[k2].msg.kind \\in ks}}",
         "MCFaults == {" + ", ".join(f'"{f}"' for f in a.faults.split(",") if f) + "}",
         "MCSym == Permutations(Sites)"]
    props = []
    if a.check != "none":
        g, var = ("PaySrc", "paySrc_c") if a.check == "src" else ("PayRcv", "payRcv_c")
        side = "Src" if a.check == "src" else "Rcv"
        assert (a.src if a.check == "src" else a.rcv) == "F", "refinement checks the fine variant"
        L.append(f"Proj == <<{'pPaySrc' if a.check == 'src' else 'pPayRcv'}, SentKinds({PAYKINDS[a.check]})>>")
        if a.negative:
            L.append(f"CBad == INSTANCE {g}_C WITH {var} <- {side}!AbsCInit")
            L.append(f"BadStep == [][CBad!Next \\/ UNCHANGED <<{side}!AbsCInit, Proj>>]_vars")
            props = ["BadStep"]
        else:
            L.append(f"CRef == INSTANCE {g}_C WITH {var} <- {side}!AbsC")
            L.append("RefInit == CRef!Init")
            L.append(f"RefStep == [][CRef!Next \\/ UNCHANGED <<{side}!AbsC, Proj>>]_vars")
            L.append("EnvSound == [][EnvStep => EPay!EnvAllowed]_vars")
            props = ["RefInit", "RefStep", "EnvSound"]
    for d in a.defs:
        L.append(d)
    L.append("====")
    (OUT / f"{mod}.tla").write_text("\n".join(L) + "\n")
    sites = [f"s{i+1}" for i in range(a.sites)]
    cfg = ["CONSTANTS", "  Faults <- MCFaults", "  Sites = {" + ", ".join(sites) + "}", "  None = None",
           "  JobId = JobId", f"  MaxLaunch = {a.launch}", f"  MaxAttempt = {a.attempt}", "  Profile = {}",
           "INIT Init", "NEXT Next"]
    for i in [x for x in a.inv.split(",") if x]:
        cfg.append(f"INVARIANT {i}")
    for p in props:
        cfg.append(f"PROPERTY {p}")
    if a.constraint:
        cfg.append(f"CONSTRAINT {a.constraint}")
    if a.symmetry and a.sites > 1:
        cfg.append("SYMMETRY MCSym")
    cfg.append("CHECK_DEADLOCK FALSE")
    (OUT / f"{mod}.cfg").write_text("\n".join(cfg) + "\n")
    return mod


def run(a, mod):
    (OUT / "results").mkdir(exist_ok=True)
    env = dict(os.environ, TLC_WORKERS=str(a.workers), TLC_HEAP=a.heap)
    extra = ["-simulate", "num=100000000", "-depth", str(a.sim)] if a.sim else []
    t0 = time.time()
    import signal
    logf = ROOT / "logs" / f"pay_{a.name}.log"
    with open(logf, "w") as fh:
        p = subprocess.Popen([str(ROOT / "scripts" / "tlc.sh"), "tlc", str(OUT), mod, f"{mod}.cfg"] + extra,
                             stdout=fh, stderr=subprocess.STDOUT, env=env, start_new_session=True)
        try:
            p.wait(timeout=a.timeout); to = False
        except subprocess.TimeoutExpired:
            to = True
            os.killpg(p.pid, signal.SIGTERM)  # tlc.sh and its JVM share the session
            try:
                p.wait(timeout=30)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL); p.wait()
    out = logf.read_text()
    r = run_mc.parse(out)
    if to and r.get("result") != "violation":
        r["result"] = "budget_stopped"
        m = re.findall(r"([\d,]+) distinct states found", out)
        if m:
            r["distinct_at_stop"] = int(m[-1].replace(",", ""))
    r.update(name=a.name, src=a.src, rcv=a.rcv, check=a.check, negative=a.negative, faults=a.faults,
             sites=a.sites, launch=a.launch, attempt=a.attempt, inv=a.inv, mode="sim" if a.sim else "bfs",
             wall_seconds=round(time.time() - t0, 1), timeout=a.timeout, workers=a.workers)
    (OUT / "results" / f"{a.name}.json").write_text(json.dumps(r, indent=1))
    print(json.dumps(r))
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--src", default="F"); ap.add_argument("--rcv", default="C")
    ap.add_argument("--check", default="src", choices=["src", "rcv", "none"])
    ap.add_argument("--negative", action="store_true")
    ap.add_argument("--faults", default="")
    ap.add_argument("--sites", type=int, default=1)
    ap.add_argument("--launch", type=int, default=1)
    ap.add_argument("--attempt", type=int, default=1, help="MaxAttempt = rounds (one tx per round)")
    ap.add_argument("--inv", default="")
    ap.add_argument("--def", dest="defs", action="append", default=[])
    ap.add_argument("--constraint")
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--workers", type=int, default=16)
    ap.add_argument("--heap", default="12g")
    ap.add_argument("--sim", type=int, default=0)
    ap.add_argument("--symmetry", action="store_true")
    a = ap.parse_args()
    mod = build(a)
    print("wrote", OUT / f"{mod}.tla")
    if a.run:
        run(a, mod)


if __name__ == "__main__":
    main()
