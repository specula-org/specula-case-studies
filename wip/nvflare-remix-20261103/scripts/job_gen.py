#!/usr/bin/env python3
"""Generate the JOB component fine variants from the frozen seed
(inputs/seeds/job/spec/actions.json, string-identical to base.tla).

  job_gen.py cp   -> spec/JobCP_F.tla   (seed group JOB_CP)
  job_gen.py sp   -> spec/JobSP_F.tla   (seed groups JOB_SCHED + JOB_SPENGINE)
  job_gen.py all

Mechanical rewrite: seed variables become fields of the group's private
record (scheduler/jobs/rpc -> jobSP_f, rm/client/resourceEnv -> jobCP_f) and
are re-exposed as same-named operators, so seed guard/update text is reused
verbatim. Seed constants are fixed to the slice profile
(inputs/vertical-slice/checks/interfaces/job/JobRefinement.tla) except
MaxRestartFailures = MaxLaunch-1 and LaunchSlots = MaxLaunch (restart hazards).
Hand-written OVERRIDES re-encode every cross-process interaction (seed
`network`, client.alive, jobs.serverAlive, the heartbeat read of
client.handle, the outcome-reply absence test, the rc/status oracles) as
messages or the allowed OS facts of Ports.tla.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "inputs" / "seeds" / "job" / "spec"
ACTS = {a["name"]: a for a in json.loads((SEED / "actions.json").read_text())}
PART = {a["name"]: a["group"] for a in json.loads(
    (ROOT / "notes" / "seeds" / "job-partition.json").read_text())["actions"]}


def short(src):
    return src.replace("nvflare/", "")


def fmt_action(name, params, lets, guards, sets, extra_unch, src, note=""):
    head = f"{name}({', '.join(params)})" if params else name
    L = [f"\\* {short(src)}" + (f"  [{note}]" if note else ""), f"{head} =="]
    ind = "    "
    if lets:
        L.append(ind + "LET " + "\n        ".join(lets) + " IN")
    for g in guards:
        L.append(ind + "/\\ " + g)
    for s in sets:
        L.append(ind + "/\\ " + s)
    if extra_unch:
        L.append(ind + "/\\ UNCHANGED <<" + ", ".join(extra_unch) + ">>")
    return "\n".join(L) + "\n"


