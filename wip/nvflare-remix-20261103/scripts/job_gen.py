# literal domains for remaining parameters (Ports-level names only)
DOM = {"rc": '{"ok", "generic", "failed", "aborted"}', "safe": "BOOLEAN"}


def rewrite_upd(expr):
    return expr


def gen_cp():
    out = [CP_HEADER]
    names = [n for n, g in PART.items() if g == "JOB_CP"]
    nexts = []
    for n in names:
        a = ACTS[n]
        o = CP_OVR.get(n, {})
        params, lets = [], []
        for p in a["params"]:
            if p == "s":
                params.append("s")
            elif p == "t":
                lets.append("t == T0")
            elif p == "g":
                pass  # comes from the status message
            else:
                params.append(p)
        guards = []
        if o.get("fault"):
            guards.append(f'"{o["fault"]}" \\in Faults')
        if o.get("k"):
            params.append("k")
        if o.get("status"):
            params.append("k")
            lets.append("g == M(k).body")
            if o["status"] == "ANY":
                guards.append("StatusMsg(s, k)")
            else:
                guards.append(f'Fresh1(s, k, "{o["status"]}")')
        gmap = o.get("g", {})
        for gd in a["guards"]:
            m = re.fullmatch(r'Msg\("(\w+)", s, t\) \\in network', gd)
            if m:
                guards.append(f'Fresh1(s, k, "{o["k"]}")')
                continue
            if gd in gmap:
                if gmap[gd] is not None:
                    guards.append(gmap[gd])
                continue
            assert "network" not in gd and ".alive" not in gd, (n, gd)
            guards.append(gd)
        guards += o.get("extra", [])
        fields = []
        for v, e in a["updates"].items():
            if v == "network":
                continue
            assert v in CP_FIELDS, (n, v)
            # client.alive is the CJ's own fact (Ports CJAlive); spawn publishes launch
            e = re.sub(r"!\[s\]\[t\]\.alive = \w+, ", "", e)
            assert ".alive" not in e and "network" not in e, (n, e)
            fields.append(f"!.{v} = {e}")
        if o.get("k") or o.get("status"):
            fields.append("!.handled = Take(s, k)")
        fields += o.get("priv", [])
        sets, unch = [], []
        if fields:
            sets.append("jobCP_f' = [jobCP_f EXCEPT " + ",\n              ".join(fields) + "]")
        else:
            unch.append("jobCP_f")
        if "network" in a["updates"] and not o.get("net") and not o.get("k") and not o.get("status"):
            raise SystemExit(f"unhandled network update in {n}")
        if o.get("net"):
            sets.append("net' = " + o["net"])
        else:
            unch.append("net")
        if o.get("port"):
            sets.append("pJobCP' = " + o["port"])
        else:
            unch.append("pJobCP")
        out.append(fmt_action(n, params, lets, guards, sets, unch, a["source"], o.get("note", "")))
        bind = [f"{p} \\in " + ("Sites" if p == "s" else "DOMAIN net" if p == "k" else DOM[p])
                for p in params]
        call = f"{n}({', '.join(params)})" if params else n
        nexts.append((bind, call))
    # group Next by binder signature
    groups = {}
    for b, c in nexts:
        groups.setdefault(tuple(b), []).append(c)
    L = ["Next =="]
    for b, cs in groups.items():
        if b:
            L.append("    \\/ \\E " + ", ".join(b) + " :")
            L.append("        " + "\n        \\/ ".join(cs))
        else:
            L.append("    \\/ " + "\n    \\/ ".join(cs))
    out.append("\n".join(L))
    out.append("=" * 77)
    (ROOT / "spec" / "JobCP_F.tla").write_text("\n".join(out) + "\n")
    print("wrote spec/JobCP_F.tla:", len(nexts), "actions")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("cp", "all"):
        gen_cp()
    if what in ("sp", "all"):
        import job_gen_sp  # noqa: F401
        job_gen_sp.gen_sp()
