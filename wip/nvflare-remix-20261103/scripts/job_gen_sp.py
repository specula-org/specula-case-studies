ROOT = G.ROOT
SP_FIELDS = ["scheduler", "jobs", "rpc"]

HEADER = r'''------------------------------ MODULE JobSP_F ------------------------------
\* Group JobSP, FINE variant. Process: SP. GENERATED by scripts/job_gen.py
\* from the job seed (inputs/seeds/job/spec/actions.json, seed groups
\* JOB_SCHED (79 actions) + JOB_SPENGINE (9), merged as the partition note
\* suggests). Seed variables scheduler, jobs, rpc are fields of jobSP_f and
\* re-exposed as operators, so guards and updates are the seed text.
\* Cross-process re-encodings (hand overrides in job_gen_sp.py):
\*   seed network -> CHECK_RESOURCES/CANCEL_RESOURCES/DEPLOY_JOB/START_JOB/
\*     ABORT_JOB/HEARTBEAT_STOP sends and RESOURCES_OK/DEPLOY_REPLY/
\*     START_REPLY/CANCEL_ACK/OUTCOME receipt (handled-key set);
\*   jobs.serverAlive (JOB_PROC) -> SJ exit fact (Ports SJExitCode) or SP kill;
\*   X5 SJ failure code written at physical exit -> recorded by ObserveExit
\*     together with the run_processes pop (server_engine.py:220-234);
\*   ServerEngineTerminate* kill a live SJ (pJobSP.sjKilled); the seed's
\*     terminate had no physical effect;
\*   X1/X2 heartbeat read of client.handle -> latest HEARTBEAT listing (HBView).
\* The port pJobSP is a function of jobSP_f (PortOf), written by every action.
\* Faults: rpcTimeout (admin waiters), admissionError, deployError, storeError,
\* launchError (SJ startup), abort (admin abort, budget 1), abortCmdError (the
\* ABORT command to the SJ raised: terminate without grace), outcomeTimeout
\* (grace expiry), archiveError; slowAdminStop lifts timing T2 (PortsJob).
EXTENDS Ports
VARIABLE jobSP_f

\* ---- slice profile of the seed constants (JobRefinement.tla) ----
Jobs == {JobId}
JobOrder == <<JobId>>
T0 == <<JobId, 1>>
Tokens == {T0}
RequiredSites == Sites
MinSites == Cardinality(Sites)
StrictStart == TRUE
MaxJobs == 1
MaxScheduleCount == 1
MinScheduleInterval == 1
MaxScheduleInterval == 1
AttemptSlots == 1
Terminal == JobTerminalStatuses
SeqSet(q) == {q[i] : i \in DOMAIN q}
Min(a,b) == IF a < b THEN a ELSE b

\* ---- seed variables as operators over the private record ----
scheduler == jobSP_f.scheduler
jobs == jobSP_f.jobs
rpc == jobSP_f.rpc

EmptyReplies == [check |-> "idle",deploy |-> "idle",start |-> "idle",cancel |-> "idle"]
EmptyJob == [status |-> "SUBMITTED", checked |-> "SUBMITTED",
             dispatch |-> {}, deployed |-> {}, active |-> {}, pending |-> {},
             outcomeKey |-> FALSE,
             serverSpawned |-> FALSE, serverRegistered |-> FALSE,
             serverWaiter |-> FALSE, serverFailed |-> FALSE, serverAborted |-> FALSE,
             serverStop |-> FALSE, serverTerminated |-> FALSE,
             startClaim |-> FALSE, claimEver |-> FALSE, running |-> FALSE, runAborted |-> FALSE, abortAck |-> FALSE,
             adminPC |-> "idle", adminRead |-> "SUBMITTED",
             completion |-> "idle", finishStatus |-> "COMPLETED",
             archiveFailed |-> FALSE, terminalPublished |-> FALSE,
             resurrected |-> FALSE, completedRemoved |-> FALSE]
InitValue ==
    [scheduler |-> [pc |-> "idle", current |-> JobId, candidates |-> <<>>,
                     issued |-> [j \in Jobs |-> 0], count |-> [j \in Jobs |-> 0],
                     persisted |-> [j \in Jobs |-> 0],
                     history |-> [j \in Jobs |-> <<>>],
                     cooldown |-> [j \in Jobs |-> FALSE], scheduled |-> {},
                     considered |-> [j \in Jobs |-> 0], result |-> "none",
                     failedPending |-> {}, blockedPending |-> {}, returnTo |-> "idle"],
     jobs |-> [j \in Jobs |-> EmptyJob],
     rpc |-> [s \in Sites |-> [t \in Tokens |-> EmptyReplies]],
     handled |-> {}, adminAborts |-> 0, admissionErrors |-> 0, ms |-> {},
     sjKilled |-> FALSE, startSent |-> {}, abortSent |-> {},
     outcomes |-> [s \in Sites |-> "none"], terminal |-> "none"]
Init == jobSP_f = InitValue

CurrentJob == scheduler.current
CurrentToken == <<CurrentJob,scheduler.issued[CurrentJob]>>
Policy(ss) == /\ Cardinality(ss) >= MinSites /\ RequiredSites \subseteq ss
ReplySites(t,k,r) == {s \in Sites : rpc[s][t][k] = r}
WaitDone(t,k,ss) == \A s \in ss : rpc[s][t][k] \notin {"idle","waiting"}

\* ---- port re-encodings ----
PortOf(f) == [sjLaunched |-> f.jobs[JobId].serverSpawned, sjKilled |-> f.sjKilled,
              startSent |-> f.startSent, abortSent |-> f.abortSent,
              outcomes |-> f.outcomes, terminal |-> f.terminal,
              status |-> f.jobs[JobId].status]
\* terminal records the class of a newly written terminal job status.
Fin(n) == [n EXCEPT !.terminal =
             IF n.jobs[JobId].status \in JobTerminalStatuses
                /\ n.jobs[JobId].status # jobSP_f.jobs[JobId].status
             THEN TerminalClass(n.jobs[JobId].status) ELSE @]
Cmd(kind, s) == Msg(kind, SP, CP(s), <<JobId, s>>, None)
CmdAll(kind, ss) == SendAll(net, {Cmd(kind, s) : s \in ss})
\* ABORT_JOB (seed Stop: five senders) and CANCEL_RESOURCES carry the sender
\* path in the id; each path sends at most once per job attempt.
CmdAllS(kind, ss, src) == SendAll(net, {Msg(kind, SP, CP(s), <<JobId, s, src>>, None) : s \in ss})
\* HEARTBEAT_STOP repeats with heartbeats; seq 2 only matters under loss.
HBStopKey(s, n) == MsgKey("HEARTBEAT_STOP", SP, CP(s), <<JobId, s, n>>)
HBStopFree(s) == HBStopKey(s, 1) \notin DOMAIN net
                 \/ ("netLoss" \in Faults /\ HBStopKey(s, 2) \notin DOMAIN net)
HBStopMsg(s) == Msg("HEARTBEAT_STOP", SP, CP(s),
                    <<JobId, s, IF HBStopKey(s, 1) \notin DOMAIN net THEN 1 ELSE 2>>, None)
FromCP(s, k, kind) == InInbox(k, SP, kind) /\ M(k).from = CP(s) /\ k \notin jobSP_f.handled
\* OS facts: the SJ process is gone (exit, crash, os._exit by an SJ group, or
\* killed by SP), and whether its return code is a failure.
SJDown == pJobSP.sjLaunched /\ (pJobSP.sjKilled \/ SJExitCode # "none")
SJCrashed == pJobSP.sjKilled \/ SJExitCode \notin {"none", "exited"}
\* Latest job listing reported by CP(s) heartbeats (0 = not listed yet; a lost
\* report is masked by the next periodic heartbeat, so loss is ignored).
HBView(s) == LET ps == {ph \in {2, 3} : MsgKey("HEARTBEAT", CP(s), SP, <<JobId, s, ph>>) \in DOMAIN net}
             IN IF ps = {} THEN 0 ELSE IF 3 \in ps THEN 3 ELSE 2

\* ---- seed invariants (base.tla:1852-1931), group-local ----
SchedulerCapacity == Cardinality(scheduler.scheduled) <= MaxJobs
RetryHistoryNotAhead == \A j \in Jobs : Len(scheduler.history[j]) <= scheduler.count[j]
AcceptedPreRunAbortPersists == \A j \in Jobs : jobs[j].abortAck => jobs[j].status="ABORTED"
NoTerminalResurrection == \A j \in Jobs : ~jobs[j].resurrected
SeedInv == SchedulerCapacity /\ RetryHistoryNotAhead
SeedHuntInv == AcceptedPreRunAbortPersists /\ NoTerminalResurrection

\* ---- abstraction to JobSP_C ----
J == JobId
FPc == scheduler.pc
BlockedDone == "exceeded" \in SeqSet(scheduler.history[J]) /\ J \notin scheduler.blockedPending
\* Milestones (ms) are recorded by the port-visible runner steps (plus the
\* running_jobs registration); coarse stages are a function of them.
AbsStage ==
    IF FPc = "failStop" THEN "failStop"
    ELSE IF FPc = "failStopWait" THEN "failCancel"
    ELSE IF FPc = "failCancelSend" THEN (IF "failStop" \in jobSP_f.ms THEN "failCancel" ELSE "failStop")
    ELSE IF FPc \in {"failCancelWait", "failStatus"} THEN "failWait"
    ELSE IF "failStatus" \in jobSP_f.ms \/ "runningWritten" \in jobSP_f.ms THEN "idle"
    ELSE IF "runReg" \in jobSP_f.ms THEN "started"
    ELSE IF "start" \in jobSP_f.ms THEN "startWait"
    ELSE IF "spawned" \in jobSP_f.ms THEN "start"
    ELSE IF "dispatched" \in jobSP_f.ms THEN "spawn"
    ELSE IF "deploy" \in jobSP_f.ms THEN "deploy"
    ELSE IF "blocked" \in jobSP_f.ms THEN "idle"
    ELSE IF "admitCancel" \in jobSP_f.ms THEN "blocked"
    ELSE IF "check" \in jobSP_f.ms THEN "check"
    ELSE "init"
Setup == FPc \in {"serverRegister", "serverWaiter", "pendingOutcomes"}
JJ == jobs[J]
AbsC == [handled |-> {k \in jobSP_f.handled : k[1] = "OUTCOME"},
         stage |-> AbsStage,
         registered |-> JJ.serverRegistered \/ FPc = "serverRegister",
         terminated |-> JJ.serverTerminated, running |-> JJ.running,
         pending |-> IF Setup THEN JJ.deployed ELSE JJ.pending,
         outcomeKey |-> JJ.outcomeKey \/ Setup,
         failed |-> JJ.serverFailed, sAborted |-> JJ.serverAborted,
         runAborted |-> JJ.runAborted,
         completion |-> CASE JJ.completion \in {"outcomeWait", "classify"} -> "wait"
                          [] JJ.completion \in {"archive", "archiveRetry", "publish"} -> "publish"
                          [] JJ.completion \in {"abortedEvent", "completedEvent", "done"} -> "done"
                          [] OTHER -> JJ.completion,
         finish |-> JJ.finishStatus,
         adminPC |-> CASE JJ.adminPC = "read" -> IF JJ.adminRead \in Terminal THEN "idle" ELSE "read"
                       [] JJ.adminPC \in {"stopWait", "markAborted"} -> "stop"
                       [] OTHER -> "idle",
         aborts |-> jobSP_f.adminAborts]
AbsCInit == [handled |-> {}, stage |-> "init",
             registered |-> FALSE, terminated |-> FALSE, running |-> FALSE,
             pending |-> {}, outcomeKey |-> FALSE, failed |-> FALSE,
             sAborted |-> FALSE, runAborted |-> FALSE,
             completion |-> "idle", finish |-> "COMPLETED",
             adminPC |-> "idle", aborts |-> 0]

'''

STOPS_REG = 'IF jobs[t[1]].serverRegistered THEN CmdAllS("ABORT_JOB", jobs[t[1]].deployed, "outcome") ELSE net'
STOPS_REG_SET = 'IF jobs[t[1]].serverRegistered THEN jobs[t[1]].deployed ELSE {}'

# o: k = (kind, body or None) consumed; net = new net expr; priv = extra private
