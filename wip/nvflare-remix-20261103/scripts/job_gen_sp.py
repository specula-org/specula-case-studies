MS = {'ServerEngineCheckClientResources': 'check', 'ServerEngineCancelClientResources': 'admitCancel', 'DefaultJobSchedulerPersistBlocked': 'blocked', 'JobRunnerDeployJob': 'deploy', 'JobRunnerWriteDispatched': 'dispatched', 'ServerEngineSpawnJob': 'spawned', 'ServerEngineStartClientJob': 'start', 'JobRunnerRegisterRunning': 'runReg', 'JobRunnerWriteRunning': 'runningWritten', 'JobRunnerFailureSendStop': 'failStop', 'JobRunnerFailureCancelResources': 'failCancel', 'JobRunnerFailureStatus': 'failStatus'}


def gen_sp():
    out = [HEADER]
    names = [n for n, g in G.PART.items() if g in ("JOB_SCHED", "JOB_SPENGINE")]
    nexts = []
    for n in names:
        a = G.ACTS[n]
        o = OVR.get(n, {})
        params, lets = [], []
        for p in a["params"]:
            if p == "s":
                params.append("s")
            elif p == "t":
                lets.append("t == T0")
            elif p == "j":
                lets.append("j == JobId")
            else:
                raise SystemExit(f"param {p} in {n}")
        guards = []
        if o.get("fault"):
            guards.append(f'"{o["fault"]}" \\in Faults')
        if o.get("budget"):
            guards.append(f"jobSP_f.{o['budget']} < 1")
        guards += o.get("extra_g", [])
        if o.get("k"):
            params.append("k")
            kind, body = o["k"]
            if body != "ANY":
                guards.append(f'FromCP(s, k, "{kind}")')
                if body is not None:
                    guards.append(f"M(k).body = {body}")
        gmap = o.get("g", {})
        for gd in a["guards"]:
            if gd in gmap:
                if gmap[gd] is not None:
                    guards.append(gmap[gd])
                continue
            m = re.fullmatch(r'Msg\("(\w+)", s, t\) \\in network', gd)
            if m and o.get("k"):
                continue
            assert "network" not in gd and "client" not in gd and "serverAlive" not in gd, (n, gd)
            guards.append(gd)
        fields = []
        for v, e in a["updates"].items():
            if v == "network":
                continue
            assert v in SP_FIELDS, (n, v)
            if v == "jobs" and o.get("ujobs"):
                e = o["ujobs"]
            for pat in o.get("drop_upd", []):
                e = re.sub(pat, "", e)
            assert "network" not in e and "serverAlive" not in e and "client" not in e, (n, e)
            fields.append(f"!.{v} = {e}")
        if "jobs" not in a["updates"] and o.get("ujobs"):
            fields.append(f"!.jobs = {o['ujobs']}")
        if o.get("k"):
            fields.append("!.handled = @ \\cup {k}")
        if o.get("budget"):
            fields.append(f"!.{o['budget']} = @ + 1")
        fields += o.get("priv", [])
        if n in MS:
            fields.append('!.ms = @ \\cup {"%s"}' % MS[n])
        sets, unch = [], []
        if "network" in a["updates"] and not o.get("net") and not o.get("k"):
            raise SystemExit(f"unhandled network update in {n}")
        if fields:
            sets.append("LET n == [jobSP_f EXCEPT " + ",\n                 ".join(fields) + "] IN\n"
                        "       /\\ jobSP_f' = Fin(n)\n       /\\ pJobSP' = PortOf(Fin(n))")
        else:
            unch += ["jobSP_f", "pJobSP"]
        if o.get("net"):
            sets.append("net' = " + o["net"])
        else:
            unch.append("net")
        out.append(G.fmt_action(n, params, lets, guards, sets, unch, a["source"], o.get("note", "")))
        bind = [f"{p} \\in " + ("Sites" if p == "s" else "DOMAIN net") for p in params]
        nexts.append((bind, f"{n}({', '.join(params)})" if params else n))
    groups = {}
    for b, c in nexts:
        groups.setdefault(tuple(b), []).append(c)
    L = ["Next =="]
    for b, cs in groups.items():
        if b:
            L.append("    \\/ \\E " + ", ".join(b) + " :")
            L.append("        " + "\n        \\/ ".join(cs))
        else:
            L.append("    \\/ " + "\n    \\/ ".join(cs))
    out.append("\n".join(L))
    out.append("=" * 77)
    (ROOT / "spec" / "JobSP_F.tla").write_text("\n".join(out) + "\n")
    print("wrote spec/JobSP_F.tla:", len(nexts), "actions")
