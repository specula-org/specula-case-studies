#!/usr/bin/env python3
"""Chunk-1 trace validation: real-code traces (tv_c1.py) replayed on Reg_C + Login_C.

Writes checks/mixes/MC_TraceC1_<scn>.tla/.cfg: the coarse Reg and Login groups with a
trace-driven environment (job launch, CP restart) and a cursor. Each Reg_C / Login_C
step either produces the next observed event or is silent (changes neither pReg nor
pLogin). Accepted = the cursor passes the last event (TraceNotAccepted violated, BFS).
Negative traces neg_<name>.json are built by mutate() from positive ones (one changed
event each); the model must reject them (BFS exhausts without passing the end).

gen_tv_c1.py [SCN ...] [--mutate] [--run]     (MIX_SPEC selects the spec directory)
"""
import json, os, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
HERE = Path(__file__).resolve().parent
MIXES = ROOT / "checks" / "mixes"
ENV = {"launch", "cprestart"}
FAULTS = {"reg_remove_live": ["adminRemove"], "reg_dead_cleanup": ["deadClient"],
          "reg_dead_admin_remove": ["deadClient", "adminRemove"], "reg_disable_enable": ["adminDisable"],
          "login_ok": [], "login_slow": ["slowRegister"], "login_disabled": ["adminDisable"]}


def tla_val(e):
    f = {"ev": f'"{e["ev"]}"'}
    return "[" + ", ".join(f"{k} |-> {v}" for k, v in f.items()) + "]"


TEMPLATE = r'''---- MODULE MC_TraceC1_@SCN@ ----
\* Generated by checks/trace/c1/gen_tv_c1.py from traces/@SCN@.json
EXTENDS Ports, TLC, Sequences
CONSTANTS s1
VARIABLES reg_c, login_c, cur
RG == INSTANCE Reg_C
LG == INSTANCE Login_C
MCFaults == {@FAULTS@}
MCProfile == {}
TR == << @TR@ >>
EnvKinds == {"launch", "cprestart"}
Fixed == <<net, pRunCJ, pTaskCJ, pPaySrc, pPayRcv, pCommSJ, pWfSJ, pTrainer, pWorker, pModel, pSwarm>>
Obs == <<pReg, pLogin>>
ObsAny == Obs' /= Obs
Match(e) ==
    CASE e.ev = "remove" -> /\ pReg.reg[s1] /\ ~pReg'.reg[s1] /\ reg_c'.pending = reg_c.pending
                            /\ pReg'.tok = pReg.tok /\ pReg'.notified = pReg.notified /\ pReg'.disabled = pReg.disabled
      [] e.ev = "disable" -> ~pReg.disabled[s1] /\ pReg'.disabled[s1] /\ ~pReg'.reg[s1]
      [] e.ev = "enable" -> pReg.disabled[s1] /\ ~pReg'.disabled[s1]
      [] e.ev = "reactivate" -> ~pReg.reg[s1] /\ pReg'.reg[s1] /\ pReg'.tok[s1] = pReg.tok[s1]
      [] e.ev = "stale" -> ~pReg.stale[s1] /\ pReg'.stale[s1]
      [] e.ev = "logout" -> pReg.reg[s1] /\ ~pReg'.reg[s1] /\ reg_c'.pending /= {}
      [] e.ev = "notify" -> <<s1, pReg.tok[s1]>> \in pReg'.notified \ pReg.notified
      [] e.ev = "relogin" -> pReg'.tok[s1] = pReg.tok[s1] + 1
      [] e.ev = "begin" -> pLogin[s1].st /= "registering" /\ pLogin'[s1].st = "registering"
      [] e.ev = "up" -> pLogin[s1].st = "registering" /\ pLogin'[s1].st = "up" /\ pLogin'[s1].adminCb
      [] e.ev = "updeaf" -> pLogin[s1].st = "registering" /\ pLogin'[s1].st = "up" /\ ~pLogin'[s1].adminCb
      [] e.ev = "exit" -> pLogin[s1].st /= "exited" /\ pLogin'[s1].st = "exited"
      [] OTHER -> FALSE
Env(e) ==
    /\ UNCHANGED <<pReg, pLogin, reg_c, login_c>> /\ UNCHANGED Fixed
    /\ CASE e.ev = "launch" -> pJobSP' = [pJobSP EXCEPT !.sjLaunched = TRUE] /\ UNCHANGED pJobCP
         [] e.ev = "cprestart" -> pJobCP' = [pJobCP EXCEPT ![s1].cpRestarted = TRUE] /\ UNCHANGED pJobSP
TInit == PortsInit /\ RG!Init /\ LG!Init /\ cur = 1
TNext ==
    \/ /\ cur <= Len(TR) /\ TR[cur].ev \in EnvKinds /\ Env(TR[cur]) /\ cur' = cur + 1
    \/ /\ \/ RG!Next /\ UNCHANGED <<login_c, pLogin>>
          \/ LG!Next /\ UNCHANGED <<reg_c, pReg>>
       /\ UNCHANGED <<pJobSP, pJobCP>> /\ UNCHANGED Fixed
       /\ IF cur <= Len(TR) /\ TR[cur].ev \notin EnvKinds /\ Match(TR[cur])
          THEN cur' = cur + 1
          ELSE ~ObsAny /\ cur' = cur
TraceNotAccepted == cur <= Len(TR)
====
'''

CFG = """CONSTANTS
  Faults <- MCFaults
  Profile <- MCProfile
  Sites = {s1}
  s1 = s1
  None = None
  JobId = JobId
  MaxLaunch = 1
  MaxAttempt = 1
INIT TInit
NEXT TNext
INVARIANT TraceNotAccepted
CHECK_DEADLOCK FALSE
"""


def base(scn):
    return scn[4:].rsplit("__", 1)[0] if scn.startswith("neg_") else scn


def gen(scn):
    ev = json.loads((HERE / "traces" / f"{scn}.json").read_text())
    name = f"TraceC1_{scn}"
    t = (TEMPLATE.replace("@SCN@", scn).replace("@FAULTS@", ", ".join(f'"{f}"' for f in FAULTS[base(scn)]))
         .replace("@TR@", ",\n        ".join(tla_val(e) for e in ev)))
    (MIXES / f"MC_{name}.tla").write_text(t)
    (MIXES / f"MC_{name}.cfg").write_text(CFG)
    return name, len(ev)


def mutate():
    """Negative controls: one changed event each (the model must reject)."""
    T = lambda n: json.loads((HERE / "traces" / f"{n}.json").read_text())
    W = lambda n, ev: (HERE / "traces" / f"{n}.json").write_text(json.dumps(ev, indent=1))
    a = T("reg_dead_admin_remove")
    W("neg_reg_dead_admin_remove__notify", a + [{"ev": "notify", "c": "site-1"}])   # a notification after the admin removal
    b = T("login_ok")
    i = next(k for k, e in enumerate(b) if e["ev"] == "relogin")
    W("neg_login_ok__up_before_token", b[:i] + [b[i + 1], b[i]] + b[i + 2:])      # serving before it has a token
    c = T("reg_disable_enable")
    W("neg_reg_disable_enable__reactivate_disabled", [e for e in c if e["ev"] != "enable"])  # re-activated while disabled
    d = T("login_disabled")
    W("neg_login_disabled__relogin", d[:-1] + [{"ev": "relogin", "c": "site-1"}, {"ev": "up", "c": "site-1"}])  # disabled name gets a token


if __name__ == "__main__":
    if "--mutate" in sys.argv:
        mutate()
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    scns = args or sorted(p.stem for p in (HERE / "traces").glob("*.json"))
    res = {}
    for s in scns:
        name, n = gen(s)
        if "--run" in sys.argv:
            import run_mc
            r = run_mc.run(name, 300, 2, "bfs", (0, 0), "4g")
            acc = r.get("result") == "violation" and r.get("violated") == "TraceNotAccepted"
            res[s] = dict(events=n, accepted=acc, result=r.get("result"), violated=r.get("violated"),
                          distinct=r.get("distinct"), error=r.get("error"))
            print(s, json.dumps(res[s]), flush=True)
    if res:
        (HERE / "tv_results.json").write_text(json.dumps(res, indent=1))
