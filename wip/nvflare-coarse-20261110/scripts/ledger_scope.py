#!/usr/bin/env python3
"""Write notes/ledger.d/90_scope_auto.py from notes/units-scope.csv (scripts/extract_units.py):
one ledger row per extracted unit of chunks not yet built. Rows of a chunk that has a
hand-reviewed ledger file (notes/ledger.d/1<k>_c<k>.py) are left out."""
import csv, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
built = {m.group(1) for f in (ROOT / "notes" / "ledger.d").glob("1*_c*.py")
         if (m := re.match(r"1\d_(c\d)", f.name))}
rows = []
for u in csv.DictReader((ROOT / "notes" / "units-scope.csv").open()):
    if u["chunk"] in built:
        continue
    status = (f"candidate {u['chunk']}: selected by the rule (STANDARD 13); review when the chunk is built"
              if u["select"] == "select" else "excluded: short-lived or local (rule, STANDARD 13); review when the chunk is built")
    rows.append((f"{u['chunk']}/{u['id']}", u["file_line"], u["unit_type"], u["chunk"].upper(), "-", "-", u["effects"],
                 status, "", u["lifetime"], u["sharing"]))
out = ROOT / "notes" / "ledger.d" / "90_scope_auto.py"
out.write_text("# GENERATED by scripts/ledger_scope.py from notes/units-scope.csv (static extraction,\n"
               "# STANDARD 13). Candidates of chunks not yet built; replaced chunk by chunk by reviewed rows.\n"
               "ROWS = [\n" + "".join(" " + repr(r) + ",\n" for r in rows) + "]\n")
print(len(rows), "rows ->", out, "; built chunks:", sorted(built))
