#!/usr/bin/env python3
"""Cause-record filters from a triage (STANDARD 10 v4): every mechanism (item | cause
records) with at least one cause record becomes a filter that exempts exactly that item
in states where all those cause records hold (for Q counterexamples: every Q item that
failed in the re-checked last state). Mechanisms without a cause record get no
filter (they keep stopping their cells: a sign that a cause record is missing).

mkfilters.py TRIAGE [TRIAGE...] --out plans/FILE.py
"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CP = {"pJobSP": "pJobSP.{f} = \"{v}\"", "pCommSJ": "pCommSJ.{f} = \"{v}\"",
      "pJobCP": "\\E c \\in Sites : pJobCP[c].{f} = \"{v}\"", "pReg": "pReg.{f} = \"{v}\"", "pWfSJ": "pWfSJ.{f} = \"{v}\"",
      "pLogin": "\\E c \\in Sites : pLogin[c].{f} = \"{v}\""}
FIELD_VAR = {f: v for v, fs in {"pJobSP": ["schedulerCrashed", "completionCrashed", "overwrite", "staleBy", "exitObs",
                                         "termEarly", "unfinalized", "failBy", "stopSkipped", "lateStart", "exitUnseen"],
                               "pJobCP": ["freedBy", "endBy", "allocLost", "gpuBy", "wsRemovedBy", "orphanBy"],
                               "pWfSJ": ["lateAccept"],
                               "pCommSJ": ["monitorCrashed", "panicBy"], "pReg": ["cleanupCrashed", "dropped"],
                               "pLogin": ["connErr"]}.items() for f in fs}
SETS = {"unmatched": "pReg.unmatched /= {}",
        "ackInferred": "\\E c \\in Sites, l \\in Launches : pTrainer[c][l].ackInferred /= {}",
        "staleStop": "\\E c \\in Sites, l \\in Launches : pTrainer[c][l].staleStop /= {}",
        "raced": "SwarmOn /\\ \\E c \\in Sites, l \\in Launches : pSwarm[c][l].gather /= None /\\ pSwarm[c][l].gather.raced /= {}",
        "poisoned": "SJModel /\\ pModel.poisoned /= {}"}


def pred(cause):
    if "=" in cause:
        f, v = cause.split("=", 1)
        if f == "stopBy":
            return f'SwarmOn /\\ \\E c \\in Sites, l \\in Launches : pSwarm[c][l].stopBy = "{v}"'
        return CP[FIELD_VAR[f]].format(f=f, v=v)
    return SETS[cause]


def main():
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    flt = {}
    for t in [a for a in sys.argv[1:] if a.endswith(".jsonl")]:
        for l in Path(t).read_text().splitlines():
            x = json.loads(l)
            if not x["causes"] or x.get("qspurious"):
                continue
            # a Q counterexample exempts every Q item that failed in it (allq, from the BFS
            # re-check): one cause, several consequences of it at quiescence
            items = sorted(set([x["item"]] + (x.get("allq") or [])) - {"Q?"})
            key = ("Q" if x["item"].startswith("Q") else x["item"])
            name = (key + "_" + "_".join(c.replace("=", "_").replace(".", "_") for c in x["causes"]))[:120]
            old = flt.get(name, {}).get("items", [])
            flt[name] = dict(items=sorted(set(old) | set(items)), pred=" /\\ ".join(f"({pred(c)})" for c in x["causes"]),
                             ledger=", ".join(c.split("=", 1)[1] if "=" in c else c for c in x["causes"]))
    out.write_text("# GENERATED by scripts/mkfilters.py: cause-record filters, one per mechanism, each\n"
                   "# exempting only its item\nFILTERS = " + json.dumps(flt, indent=1) + "\n")
    print(len(flt), "filters ->", out)


if __name__ == "__main__":
    main()
